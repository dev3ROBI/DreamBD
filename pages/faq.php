            <h2>How do I change my profile information?</h2>
            <p>Open your profile page, go to the profile settings/preferences area, then update the fields you want to change. Theme selection can also be changed from the navbar settings popup.</p>
        </article>
        <article class="info-faq-card">
            <h2>Who can see my posts?</h2>
            <p>Post visibility depends on the privacy option you choose. Public posts can be seen widely, friends posts are visible to accepted friends, and private posts stay limited.</p>
        </article>
        <article class="info-faq-card">
            <h2>How do direct messages work?</h2>
            <p>You can open a conversation from the Messages page or from a user profile. Messages support reactions, replies, image sharing, pinned messages, and unread counts.</p>
        </article>
        <article class="info-faq-card">
            <h2>Why am I not seeing some community posts?</h2>
            <p>The home feed uses ranking to show more relevant posts first. The Community page shows a broader post list, including more public content.</p>
        </article>
        <article class="info-faq-card">
            <h2>What happens when I report content?</h2>
            <p>Reports can be reviewed by the site owner or moderator workflow. Reported content may be flagged for review, removed, or used to identify abusive behavior.</p>
        </article>
        <article class="info-faq-card">
            <h2>How do I switch dark mode and light mode?</h2>
            <p>Use the theme icon in the navbar or open the settings popup. If you choose Auto, DreamBD will follow your device preference.</p>
        </article>
